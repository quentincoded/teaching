const listeners = new Set();

export function getLang() {
  return document.documentElement.lang === 'en' ? 'en' : 'de';
}

export function t(key, vars = {}) {
  const s = STRINGS[getLang()][key] ?? STRINGS.de[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

/** Pick the right language from a {de, en} object, or from obj[field] / obj[field_en]. */
export function pick(obj, field) {
  if (!obj) return '';
  const lang = getLang();
  if (field) return (lang === 'en' && obj[`${field}_en`]) || obj[field] || '';
  if (typeof obj === 'string') return obj;
  return obj[lang] ?? obj.de ?? '';
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.dataset.i18nAttr.split(';').forEach((pair) => {
      const [attr, key] = pair.split(':').map((s) => s.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    });
  });
}

export function setLang(lang) {
  document.documentElement.lang = lang;
  try { localStorage.setItem('lang', lang); } catch (e) { /* storage unavailable */ }
  applyI18n();
  listeners.forEach((fn) => fn(lang));
}

export function onLangChange(fn) { listeners.add(fn); }
